#!/usr/bin/env python3
"""Generate the rule digests from `docs/rules/rules.toml`, the single source of the rule data.

    python3 scripts/gen_rules_md.py           # write NLAlib/<Topic>/RULES.md and docs/rules/DIGEST.md
    python3 scripts/gen_rules_md.py --check   # fail if a generated file is stale (CI, stage_check)

`NLAlib/<Topic>/RULES.md` lists the rules a file of that topic must keep, the topic's own first
(rules scoped to it, and library-wide rules whose `home` names it), then the library-wide ones by
area, each linked to its CONTRIBUTING section. `docs/rules/DIGEST.md` is every error rule in one
line, small enough for an agent brief to include whole (CONTRIBUTING §11).
"""
import argparse
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOML = ROOT / 'docs' / 'rules' / 'rules.toml'
DIGEST = ROOT / 'docs' / 'rules' / 'DIGEST.md'
AREAS = 'FPSTVBDMCRGN'
HEADER = '<!-- Generated by scripts/gen_rules_md.py from docs/rules/rules.toml; do not edit. -->\n'


def rid_key(rid):
    return (AREAS.index(rid[0]), int(rid[1:]))


def anchors(contrib):
    """{'2': '2-layout', '5.2': '52-shape', …} from CONTRIBUTING's numbered headings."""
    out = {}
    for m in re.finditer(r'^#{2,3} (\d+(?:\.\d+)?)\.? (.*)$', contrib, re.M):
        title = f'{m.group(1)} {m.group(2)}'.lower()
        slug = re.sub(r'[^\w\- ]', '', title).replace(' ', '-')
        out[m.group(1)] = slug
    return out


def section_ref(sec, anc, refs, prefix):
    """`[§3]`, a reference link to CONTRIBUTING's heading, recorded in `refs`."""
    m = re.search(r'§(\d+(?:\.\d+)?)', sec)
    if not m or m.group(1) not in anc:
        return sec
    refs[f'§{m.group(1)}'] = f'{prefix}CONTRIBUTING.md#{anc[m.group(1)]}'
    return f'[§{m.group(1)}]' + sec[m.end():]


def applies(r, topic):
    path = f'NLAlib/{topic}'
    if r['scope'] != 'library' and path not in r['scope']:
        return False
    return path not in r.get('exclude', []) and path not in r.get('exempt', [])


def own(r, topic):
    path = f'NLAlib/{topic}'
    return (r['scope'] != 'library' and path in r['scope']) or path in r.get('home', [])


def level(r):
    return '' if r['severity'] == 'error' else f' ({r["severity"]})'


def topic_md(topic, rules, anc):
    pre, refs = '../../', {}
    path = f'NLAlib/{topic}'
    mine = [r for r in rules if applies(r, topic) and own(r, topic)]
    exempt = [r for r in rules if path in r.get('exempt', [])]
    rest = [r for r in rules if applies(r, topic) and not own(r, topic)]
    out = [HEADER, f'# Rules for `{path}`', '',
           f'The rules a file in `{path}` (and `NLAlibScaffold/{topic}`) keeps, generated from',
           '`docs/rules/rules.toml`. Errors fail CI; a warning is a heuristic review list; a review',
           'rule has no check. The reasons are in CONTRIBUTING at the linked section. Check a file',
           'with `python3 scripts/check_rules.py --files <file>`; an agent brief includes this file',
           'and `docs/rules/DIGEST.md`.', '']
    if mine or exempt:
        out += ['## This topic', '']
        for r in mine:
            out.append(f'- **{r["id"]}**{level(r)} {r["statement"]}. Fix: {r["fix"]}. '
                       f'{section_ref(r["section"], anc, refs, pre)}')
        for r in exempt:
            out.append(f'- **{r["id"]}** does not apply here while **{r["exempt_while"]}** holds. '
                       f'{section_ref(r["section"], anc, refs, pre)}')
        out.append('')
    out += ['## Every topic', '']
    area = None
    for r in rest:
        if r['area'] != area:
            if area is not None:
                out.append('')
            area = r['area']
            out += [f'### {area[0].upper() + area[1:]}', '']
        out.append(f'- **{r["id"]}**{level(r)} {r["statement"]}. '
                   f'{section_ref(r["section"], anc, refs, pre)}')
    out.append('')
    out += [f'[{k}]: {v}' for k, v in sorted(refs.items(), key=lambda kv: [int(x) for x in kv[0][1:].split('.')])]
    return '\n'.join(out) + '\n'


def digest_md(rules):
    out = [HEADER, '# Rules digest\n',
           'Every error rule of `docs/rules/rules.toml` in one line; an agent brief includes this file',
           'whole, with the topic\'s `NLAlib/<Topic>/RULES.md` (CONTRIBUTING §11). Warnings and review',
           'rules are in the topic files; the reasons are in CONTRIBUTING.\n']
    for r in rules:
        if r['severity'] != 'error':
            continue
        where = '' if r['scope'] == 'library' else ' [' + ', '.join(
            s.removeprefix('NLAlib/') for s in r['scope']) + ' only]'
        out.append(f'- {r["id"]} {r["statement"]}{where}.')
    return '\n'.join(out) + '\n'


def generate(root=ROOT):
    rules = sorted(tomllib.loads((root / 'docs/rules/rules.toml').read_text())['rule'],
                   key=lambda r: rid_key(r['id']))
    anc = anchors((root / 'CONTRIBUTING.md').read_text())
    files = {root / 'docs/rules/DIGEST.md': digest_md(rules)}
    for d in sorted((root / 'NLAlib').iterdir()):
        if d.is_dir():
            files[d / 'RULES.md'] = topic_md(d.name, rules, anc)
    return files


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--check', action='store_true', help='fail if a generated file is stale')
    ap.add_argument('--root', type=Path, default=ROOT)
    a = ap.parse_args(argv)
    files = generate(a.root)
    if a.check:
        stale = [p for p, t in files.items() if not p.exists() or p.read_text() != t]
        for p in stale:
            print(f'gen_rules_md: {p.relative_to(a.root)} is stale; run python3 scripts/gen_rules_md.py')
        if not stale:
            print(f'gen_rules_md: {len(files)} generated files current')
        return 1 if stale else 0
    for p, t in files.items():
        p.write_text(t)
    print(f'gen_rules_md: wrote {len(files)} files')
    return 0


if __name__ == '__main__':
    sys.exit(main())
