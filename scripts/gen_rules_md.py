#!/usr/bin/env python3
"""Generate the rule digests from `docs/rules/rules.toml`, the single source of the rule data.

    python3 scripts/gen_rules_md.py           # write NLAlib/<Topic>/RULES.md and docs/rules/DIGEST.md
    python3 scripts/gen_rules_md.py --check   # fail if a generated file is stale (CI, stage_check)

`NLAlib/<Topic>/RULES.md` lists the rules a file of that topic must keep, the topic's own first
(rules scoped to it, and library-wide rules whose `home` names it), then the library-wide ones by
area, each linked to the section of the contributor guide that states it. `docs/rules/DIGEST.md`
is every error rule in one line, small enough for an agent brief to include whole
(CONTRIBUTING.md, AI agents).
"""
import argparse
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOML = ROOT / 'docs' / 'rules' / 'rules.toml'
DIGEST = ROOT / 'docs' / 'rules' / 'DIGEST.md'
AREAS = 'FPSTVBDMCRAGEN'
GUIDES = 'docs/contributing'
HEADER = '<!-- Generated by scripts/gen_rules_md.py from docs/rules/rules.toml; do not edit. -->\n'


def rid_key(rid):
    return (AREAS.index(rid[0]), int(rid[1:]))


def anchors(contrib):
    """{'1': '1-types', '2': '2-shape', …} from a guide's numbered headings."""
    out = {}
    for m in re.finditer(r'^#{2,3} (\d+(?:\.\d+)?)\.? (.*)$', contrib, re.M):
        title = f'{m.group(1)} {m.group(2)}'.lower()
        slug = re.sub(r'[^\w\- ]', '', title).replace(' ', '-')
        out[m.group(1)] = slug
    return out


def guide_anchors(root):
    """{stem: anchors} for each guide of docs/contributing."""
    return {f.stem: anchors(f.read_text()) for f in sorted((root / GUIDES).glob('*.md'))}


def section_ref(sec, anc, refs, prefix):
    """`[statements §2]`, a reference link to the guide's heading, recorded in `refs`. A section is
    a guide's name, `CONTRIBUTING` for the hub, then an optional `§n` and words."""
    m = re.match(r'(\w+)(?: §(\d+))?', sec)
    stem, num = m.group(1), m.group(2)
    if stem == 'CONTRIBUTING':
        target = f'{prefix}CONTRIBUTING.md' + ('#ground-rules' if 'ground rule' in sec else '')
    elif stem in anc and (num is None or num in anc[stem]):
        target = f'{prefix}{GUIDES}/{stem}.md' + (f'#{anc[stem][num]}' if num else '')
    else:
        return sec
    label = stem + (f' §{num}' if num else '')
    refs[label] = target
    return f'[{label}]' + sec[m.end():]


def applies(r, topic):
    path = f'NLAlib/{topic}'
    if r['scope'] != 'library' and path not in r['scope']:
        return False
    return path not in r.get('exclude', []) and path not in r.get('exempt', [])


def own(r, topic):
    path = f'NLAlib/{topic}'
    return (r['scope'] != 'library' and path in r['scope']) or path in r.get('home', [])


def level(r):
    return '' if r['severity'] == 'error' else f' ({r["severity"]})'


def fmt_layer(n):
    return str(int(n)) if n == int(n) else str(n)


def allow_entries(root):
    """{topic: [(rule, declaration or file, reason)]} of `scripts/rules_allow.toml` and
    `scripts/names_allow.toml`, by the topic folder that declares the entry."""
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import leansrc
    where = {}
    for f in sorted((root / 'NLAlib').rglob('*.lean')):
        topic = f.relative_to(root / 'NLAlib').parts[0]
        for d in leansrc.parse(f.read_text())['decls']:
            if d['full']:
                where.setdefault(d['full'], topic)
    out = {}
    for file, key in (('scripts/rules_allow.toml', 'decl'), ('scripts/names_allow.toml', 'name')):
        for e in tomllib.loads((root / file).read_text()).get('allow', []):
            if 'path' in e:
                what, topic = e['path'], e['path'].split('/')[1] if e['path'].startswith('NLAlib/') else None
            else:
                what = e[key]
                topic = where.get(what) or where.get(f'NLAlib.{what}')
            if topic:
                out.setdefault(topic, []).append((e['rule'], what, e['reason']))
    return {k: sorted(v, key=lambda x: (rid_key(x[0]), x[1])) for k, v in out.items()}


def topic_md(topic, rules, anc, layers, allows):
    pre, refs = '../../', {}
    path = f'NLAlib/{topic}'
    mine = [r for r in rules if applies(r, topic) and own(r, topic)]
    exempt = [r for r in rules if path in r.get('exempt', [])]
    rest = [r for r in rules if applies(r, topic) and not own(r, topic)]
    out = [HEADER, f'# Rules for `{path}`', '',
           f'The rules a file in `{path}` keeps, generated from',
           '`docs/rules/rules.toml`. Errors fail CI; a warning is a heuristic review list; a review',
           'rule has no check. The reasons are in the contributor guide at the linked section. Check a file',
           'with `python3 scripts/check_rules.py --files <file>`; an agent brief includes this file',
           'and `docs/rules/DIGEST.md`.', '']
    layer = layers.get(topic)
    if layer or mine or exempt or allows.get(topic):
        out += ['## This topic', '']
        if layer:
            out.append(f'- **Layer {fmt_layer(layer["layer"])}** (`docs/rules/layers.toml`): a file imports '
                       'only modules of its own layer and lower (**P1**). [layout §1]')
            refs['layout §1'] = f'{pre}{GUIDES}/layout.md#{anc["layout"]["1"]}'
        why = {}
        if layer and 'imports' in layer:
            if any(r['id'] == layer['rule'] for r in mine):
                why[layer['rule']] = f' Why: {layer["reason"]}.'
            else:
                names = ['Mathlib'] + [f'`NLAlib.{f}`' for f in sorted(set(layer['imports']) | {topic})]
                only = ', '.join(names[:-1]) + ' and ' + names[-1]
                out.append(f'- **{layer["rule"]}** A file here imports only {only}: {layer["reason"]}.')
        for r in mine:
            out.append(f'- **{r["id"]}**{level(r)} {r["statement"]}. Fix: {r["fix"]}.{why.get(r["id"], "")} '
                       f'{section_ref(r["section"], anc, refs, pre)}')
        for r in exempt:
            out.append(f'- **{r["id"]}** does not apply here while **{r["exempt_while"]}** holds: '
                       f'{r["exempt_reason"]}. {section_ref(r["section"], anc, refs, pre)}')
        if allows.get(topic):
            out += ['', 'Allowlisted here (`scripts/rules_allow.toml`, `scripts/names_allow.toml`), each '
                    'excused from one rule:', '']
            out += [f'- **{rid}** `{what}`: {reason}' for rid, what, reason in allows[topic]]
        out.append('')
    out += ['## Every topic', '']
    area = None
    for r in rest:
        if r['area'] != area:
            if area is not None:
                out.append('')
            area = r['area']
            out += [f'### {area[0].upper() + area[1:]}', '']
        out.append(f'- **{r["id"]}**{level(r)} {r["statement"]}. '
                   f'{section_ref(r["section"], anc, refs, pre)}')
    out.append('')
    out += [f'[{k}]: {v}' for k, v in sorted(refs.items())]
    return '\n'.join(out) + '\n'


def digest_md(rules):
    out = [HEADER, '# Rules digest\n',
           'Every error rule of `docs/rules/rules.toml` in one line; an agent brief includes this file',
           'whole, with the topic\'s `NLAlib/<Topic>/RULES.md` (CONTRIBUTING.md, AI agents). Warnings and review',
           'rules are in the topic files; the reasons are in the contributor guide.\n']
    for r in rules:
        if r['severity'] != 'error':
            continue
        where = '' if r['scope'] == 'library' else ' [' + ', '.join(
            s.removeprefix('NLAlib/') for s in r['scope']) + ' only]'
        out.append(f'- {r["id"]} {r["statement"]}{where}.')
    return '\n'.join(out) + '\n'


def generate(root=ROOT):
    rules = sorted(tomllib.loads((root / 'docs/rules/rules.toml').read_text())['rule'],
                   key=lambda r: rid_key(r['id']))
    anc = guide_anchors(root)
    layers = {e['folder']: e for e in tomllib.loads((root / 'docs/rules/layers.toml').read_text())['layer']}
    allows = allow_entries(root)
    files = {root / 'docs/rules/DIGEST.md': digest_md(rules)}
    for d in sorted((root / 'NLAlib').iterdir()):
        if d.is_dir():
            files[d / 'RULES.md'] = topic_md(d.name, rules, anc, layers, allows)
    return files


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--check', action='store_true', help='fail if a generated file is stale')
    ap.add_argument('--root', type=Path, default=ROOT)
    a = ap.parse_args(argv)
    files = generate(a.root)
    if a.check:
        stale = [p for p, t in files.items() if not p.exists() or p.read_text() != t]
        for p in stale:
            print(f'gen_rules_md: {p.relative_to(a.root)} is stale; run python3 scripts/gen_rules_md.py')
        if not stale:
            print(f'gen_rules_md: {len(files)} generated files current')
        return 1 if stale else 0
    for p, t in files.items():
        p.write_text(t)
    print(f'gen_rules_md: wrote {len(files)} files')
    return 0


if __name__ == '__main__':
    sys.exit(main())
